// Агрегация статусов STT нескольких провайдеров сессии в один статус для клиента (LS-04).
//
// В режиме per-track у каждого участника свой экземпляр DeepgramSTT со своим
// onStatusChange — статусы приходят из нескольких независимых источников.
// Слать клиенту статус каждого провайдера как есть означало бы дребезг: пять
// участников — пять сообщений на каждое реконнект-событие любого из них, и
// клиенту пришлось бы самому решать, что с этим делать. aggregateSttStatus()
// сводит список статусов сессии в один, который решает, показывать ли
// пользователю индикатор проблемы.
//
// Правила:
//  - пустой список (ни одной дорожки/провайдера ещё нет) → 'ok': нечему сообщать;
//  - хотя бы один 'reconnecting' → 'reconnecting' — идёт восстановление хотя бы
//    одной дорожки, победа приоритетнее 'failed', потому что процесс ещё жив;
//  - все статусы 'failed' → 'failed' — распознавание не идёт ни по одной
//    дорожке (но запись аудио продолжается независимо от STT, встреча не
//    потеряна — см. комментарий у SttStatusMessage в websocket-protocol.ts);
//  - смешение 'failed' и 'ok' (часть дорожек безвозвратно упала, часть жива) —
//    решено трактовать как 'reconnecting', а не 'ok': с точки зрения
//    пользователя по упавшей дорожке текст больше не появится, это не
//    "всё хорошо", но это и не тотальный отказ встречи — 'reconnecting'
//    точнее передаёт "распознавание частично барахлит", чем молчаливое 'ok',
//    которое скрыло бы реальную деградацию;
//  - иначе (все 'ok') → 'ok'.
import type { STTStatus } from './types.js';

export function aggregateSttStatus(statuses: STTStatus[]): STTStatus {
  if (statuses.length === 0) return 'ok';
  if (statuses.some((status) => status === 'reconnecting')) return 'reconnecting';
  if (statuses.every((status) => status === 'failed')) return 'failed';
  if (statuses.some((status) => status === 'failed')) return 'reconnecting';
  return 'ok';
}
