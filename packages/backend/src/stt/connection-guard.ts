// Отсекаем результаты, пришедшие от уже неактуального соединения к Deepgram.
//
// После tryReconnect() поле DeepgramSTT.connection указывает на НОВОЕ соединение,
// но обработчики результатов старого соединения остаются подписаны и могут
// сработать позже (то же аудио параллельно распознаёт и новое соединение).
// Такой результат — не просто дубликат: смещение offset-шкалы (stream-clock.ts)
// на момент его прихода уже посчитано для НОВОГО соединения и не подходит
// для позиции, которую отдало старое (см. LS-30) — применение офсета к нему
// портит монотонность startSec. Поэтому результат нужно отбросить целиком,
// не пропуская через offset вообще.
//
// Логика — тривиальная проверка идентичности, но вынесена в отдельную функцию,
// чтобы её можно было протестировать без обращения к Deepgram SDK.
export function isActiveConnection(current: unknown, source: unknown): boolean {
  return current === source;
}
